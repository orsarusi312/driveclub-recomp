static inline const DcMemoryProfile *dc_memory_profile(const unsigned char *image, size_t size) {
    if (!image) return NULL;
    for (size_t i=0;i<sizeof(dc_memory_profiles)/sizeof(dc_memory_profiles[0]);++i) {
        const DcMemoryProfile *profile=&dc_memory_profiles[i];
        size_t j=0;
        for (;j<4;++j) {
            const DcMemoryPatch *p=&profile->writes[j];
            if (p->offset>size || p->length>size-p->offset || memcmp(image+p->offset,p->bytes,p->length)) break;
        }
        if (j==4) return profile;
    }
    return NULL;
}
static inline int dc_memory_profile_check(const unsigned char *image, size_t size, uint64_t pool, FILE *log) {
    const DcMemoryProfile *p=dc_memory_profile(image,size);
    if (!p) return 1;
    const uint64_t mib=UINT64_C(1024)*1024;
    fprintf(log,"Memory profile: %s; direct pool=%" PRIu64 " MiB; VideoPrivate=%u MiB; launcher budget=%u MiB\n",p->name,pool/mib,p->video_mib,p->mib);
    /* Reject only a provably impossible allocation. Custom budgets are not
     * rejected merely for differing from the launcher. Passing this bound does
     * not prove the remaining heaps will fit; the launcher budget is preferred. */
    if (pool >= p->video_mib*mib) return 1;
    fprintf(log,"STOP: memory patch/direct-pool mismatch: VideoPrivate alone exceeds the entire direct pool. The launcher pairs this patch with BB_DMEM_MB=%u. Set $env:BB_DMEM_MB='%u' before a direct PowerShell launch, or use the launcher. Prepared files and game assets have not been changed.\n",p->mib,p->mib);
    return 0;
}
